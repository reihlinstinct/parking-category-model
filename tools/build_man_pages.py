"""Generate the Linux man pages from cli_spec.py (issue #26).

The pages are generated, not hand-written: edit cli_spec.py and re-run.

Usage:
  python tools/build_man_pages.py                  # regenerate man/man1/*.1 in place
  python tools/build_man_pages.py --check          # exit 1 if committed pages are stale
  python tools/build_man_pages.py --dir DIR        # write/compare against DIR instead
  python tools/build_man_pages.py --tarball OUT.tar.gz   # distributable man package

Standard library only. No network.
"""

from __future__ import annotations

import argparse
import gzip
import io
import sys
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from parking_category_model import cli_spec  # noqa: E402

DEFAULT_DIR = ROOT / "man" / "man1"
HEADER_COMMENT = '.\\" Generated by tools/build_man_pages.py from cli_spec.py; do not edit.'
PAGE_GLOB = f"{cli_spec.PROGRAM}*.1"


def esc(text: str) -> str:
    """Escape a text fragment for roff."""
    return text.replace("\\", r"\e").replace("-", r"\-")


def text_line(text: str) -> str:
    """A free-text roff line: a leading . or ' would be read as a request."""
    if text[:1] in (".", "'"):
        return "\\&" + esc(text)
    return esc(text)


def page_name(command: str) -> str:
    return f"{cli_spec.PROGRAM}-{command}.1"


def th(title: str) -> list[str]:
    return [
        f'.TH "{esc(title.upper())}" "1" "{esc(cli_spec.MAN_DATE)}" '
        f'"{esc(cli_spec.PROGRAM)} {esc(cli_spec.VERSION)}" "{esc(cli_spec.MANUAL)}"',
    ]


def render(command: cli_spec.Command) -> str:
    """Render one command as a roff man page."""
    title = f"{cli_spec.PROGRAM}-{command.name}"
    lines: list[str] = [HEADER_COMMENT]
    lines += th(title)
    lines.append(".SH NAME")
    lines.append(f"{esc(title)} \\- {esc(command.summary)}")
    lines.append(".SH SYNOPSIS")
    usage = f"python -m {command.module}"
    for opt in command.options:
        token = opt.flag if opt.metavar is None else f"{opt.flag} {opt.metavar}"
        usage += f" {token}" if opt.required else f" [{token}]"
    lines.append(".B " + esc(usage))
    lines.append(".SH DESCRIPTION")
    for para in command.description:
        lines.append(".PP")
        lines.append(text_line(para))
    if command.options:
        lines.append(".SH OPTIONS")
        for opt in command.options:
            flag = opt.flag if opt.metavar is None else f"{opt.flag} {opt.metavar}"
            lines.append(f".TP\n.B {esc(flag)}")
            suffix = " (required)" if opt.required else ""
            lines.append(text_line(opt.help + suffix))
    if command.examples:
        lines.append(".SH EXAMPLES")
        for cmd, note in command.examples:
            lines.append(".PP")
            lines.append(text_line(cmd))
            lines.append(".RS")
            lines.append(text_line(note))
            lines.append(".RE")
    lines.append(".SH EXIT STATUS")
    lines.append(".TP\n.B 0")
    lines.append("Success.")
    lines.append(".TP\n.B 1")
    lines.append("The command failed (e.g. missing data, unreadable model); "
                 "Python reports the error and exits 1.")
    lines.append(".TP\n.B 2")
    lines.append("Command-line usage error (invalid or missing arguments).")
    lines.append(".SH SEE ALSO")
    others = [c for c in cli_spec.COMMANDS if c != command.name]
    for i, c in enumerate(others):
        comma = "," if i < len(others) - 1 else ""
        lines.append(f".BR {esc(cli_spec.PROGRAM + '-' + c)} (1){comma}")
    lines.append(".BR man (1)")
    return "\n".join(lines) + "\n"


def render_all() -> dict[str, str]:
    return {page_name(c.name): render(c) for c in cli_spec.COMMANDS.values()}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="exit 1 if committed pages are stale")
    parser.add_argument("--dir", type=Path, default=None,
                        help="write/compare against DIR instead of man/man1")
    parser.add_argument("--tarball", type=Path, default=None,
                        help="also write a distributable .tar.gz of the pages")
    args = parser.parse_args(argv)

    target = args.dir or DEFAULT_DIR
    pages = render_all()

    if args.check:
        stale = []
        existing = {p.name: p.read_text(encoding="utf-8") for p in target.glob(PAGE_GLOB)}
        for name, body in pages.items():
            if existing.get(name) != body:
                stale.append(name)
        for name in existing:
            if name not in pages:
                stale.append(f"{name} (untracked by cli_spec)")
        if stale:
            print("stale man pages:", ", ".join(sorted(stale)))
            return 1
        print(f"OK: {len(pages)} man page(s) up to date")
        return 0

    target.mkdir(parents=True, exist_ok=True)
    for name, body in pages.items():
        (target / name).write_text(body, encoding="utf-8")
    print(f"wrote {len(pages)} man page(s) to {target}")

    if args.tarball is not None:
        # Deterministic: uncompressed tar built in memory, then gzipped with a
        # zeroed mtime so identical pages give an identical archive.
        raw = io.BytesIO()
        with tarfile.open(fileobj=raw, mode="w") as tar:
            for name, body in sorted(pages.items()):
                data = body.encode("utf-8")
                info = tarfile.TarInfo(f"man1/{name}")
                info.size = len(data)
                info.mtime = 0
                tar.addfile(info, io.BytesIO(data))
        with gzip.GzipFile(filename="", mode="wb", fileobj=args.tarball.open("wb"), mtime=0) as gz:
            gz.write(raw.getvalue())
        print(f"wrote tarball {args.tarball}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
